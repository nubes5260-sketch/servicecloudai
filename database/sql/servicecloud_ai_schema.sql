-- (1) Ámbito del rol: los roles globales (ADMIN_SAAS) solo para usuarios sin organización;
--     los demás solo para usuarios de una organización.
CREATE OR REPLACE FUNCTION servicecloud_validar_ambito_rol() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_global BOOLEAN;
  v_org BIGINT;
BEGIN
  SELECT es_global INTO v_global FROM roles WHERE id = NEW.rol_id;
  SELECT organizacion_id INTO v_org FROM usuarios WHERE id = NEW.usuario_id;
  IF v_global AND v_org IS NOT NULL THEN
    RAISE EXCEPTION 'El rol global % solo puede asignarse a usuarios de la plataforma (sin organización)', NEW.rol_id;
  ELSIF NOT v_global AND v_org IS NULL THEN
    RAISE EXCEPTION 'El rol % requiere que el usuario pertenezca a una organización', NEW.rol_id;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_usuarios_roles_ambito ON usuarios_roles;
CREATE TRIGGER trg_usuarios_roles_ambito BEFORE INSERT OR UPDATE ON usuarios_roles
 FOR EACH ROW EXECUTE FUNCTION servicecloud_validar_ambito_rol();

-- (7) Incidencia ligada a un problema y a un ticket: el ticket queda vinculado al mismo problema,
--     así los dos caminos (incidencia→problema y ticket↔problema) nunca se contradicen.
CREATE OR REPLACE FUNCTION servicecloud_sincronizar_problema_ticket() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.problema_id IS NOT NULL AND NEW.ticket_id IS NOT NULL THEN
    INSERT INTO problemas_tickets(organizacion_id, problema_id, ticket_id)
    VALUES (NEW.organizacion_id, NEW.problema_id, NEW.ticket_id)
    ON CONFLICT (problema_id, ticket_id) DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_incidencias_problema_ticket ON incidencias;
CREATE TRIGGER trg_incidencias_problema_ticket AFTER INSERT OR UPDATE OF problema_id, ticket_id ON incidencias
 FOR EACH ROW EXECUTE FUNCTION servicecloud_sincronizar_problema_ticket();

-- (8) Jerarquía de categorías sin bucles: una categoría no puede ser ancestro de sí misma.
CREATE OR REPLACE FUNCTION servicecloud_validar_jerarquia_categoria() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.padre_id IS NOT NULL AND EXISTS (
    WITH RECURSIVE ancestros(id) AS (
      SELECT NEW.padre_id
      UNION
      SELECT c.padre_id FROM categorias_tickets c JOIN ancestros a ON c.id = a.id WHERE c.padre_id IS NOT NULL
    )
    SELECT 1 FROM ancestros WHERE id = NEW.id
  ) THEN
    RAISE EXCEPTION 'La categoría % no puede depender de sí misma (ciclo en padre_id)', NEW.id;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_categorias_tickets_ciclo ON categorias_tickets;
CREATE TRIGGER trg_categorias_tickets_ciclo BEFORE INSERT OR UPDATE OF padre_id ON categorias_tickets
 FOR EACH ROW EXECUTE FUNCTION servicecloud_validar_jerarquia_categoria();

