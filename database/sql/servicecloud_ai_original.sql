CREATE OR REPLACE FUNCTION servicecloud_set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  NEW.actualizado_en = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_organizaciones_updated_at ON organizaciones;
CREATE TRIGGER trg_organizaciones_updated_at BEFORE UPDATE ON organizaciones FOR EACH ROW EXECUTE FUNCTION servicecloud_set_updated_at();
DROP TRIGGER IF EXISTS trg_usuarios_updated_at ON usuarios;
CREATE TRIGGER trg_usuarios_updated_at BEFORE UPDATE ON usuarios FOR EACH ROW EXECUTE FUNCTION servicecloud_set_updated_at();
DROP TRIGGER IF EXISTS trg_tickets_updated_at ON tickets;
CREATE TRIGGER trg_tickets_updated_at BEFORE UPDATE ON tickets FOR EACH ROW EXECUTE FUNCTION servicecloud_set_updated_at();
DROP TRIGGER IF EXISTS trg_articulos_conocimiento_updated_at ON articulos_conocimiento;
CREATE TRIGGER trg_articulos_conocimiento_updated_at BEFORE UPDATE ON articulos_conocimiento FOR EACH ROW EXECUTE FUNCTION servicecloud_set_updated_at();

