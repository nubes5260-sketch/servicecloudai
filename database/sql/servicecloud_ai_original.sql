BEGIN;


CREATE TABLE IF NOT EXISTS planes_saas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(80) NOT NULL UNIQUE,
 precio_mensual DECIMAL(12,2) NOT NULL DEFAULT 0, limite_usuarios INTEGER NULL,
 limite_activos INTEGER NULL, limite_tickets INTEGER NULL,
 caracteristicas JSONB NULL, activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS organizaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo VARCHAR(30) UNIQUE,
 razon_social VARCHAR(180) NOT NULL, ruc VARCHAR(20) NULL UNIQUE, sector VARCHAR(100),
 email VARCHAR(180), telefono VARCHAR(30), direccion VARCHAR(255),
 plan_id BIGINT NULL, estado VARCHAR(40) CHECK (estado IN ('evaluacion','activa','suspendida','inactiva')) NOT NULL DEFAULT 'evaluacion',
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_org_plan FOREIGN KEY(plan_id) REFERENCES planes_saas(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS roles (
 id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo VARCHAR(60) NOT NULL UNIQUE,
 nombre VARCHAR(100) NOT NULL, descripcion VARCHAR(255), es_global BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS permisos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo VARCHAR(100) NOT NULL UNIQUE,
 descripcion VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS roles_permisos (
 rol_id SMALLINT NOT NULL, permiso_id BIGINT NOT NULL,
 PRIMARY KEY(rol_id,permiso_id),
 FOREIGN KEY(rol_id) REFERENCES roles(id) ON DELETE CASCADE,
 FOREIGN KEY(permiso_id) REFERENCES permisos(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NULL,
 nombre VARCHAR(150) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, telefono VARCHAR(30), cargo VARCHAR(100),
 estado VARCHAR(40) CHECK (estado IN ('activo','inactivo','bloqueado')) NOT NULL DEFAULT 'activo',
 ultimo_acceso TIMESTAMP NULL, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS usuarios_roles (
 usuario_id BIGINT NOT NULL, rol_id SMALLINT NOT NULL,
 PRIMARY KEY(usuario_id,rol_id),
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 FOREIGN KEY(rol_id) REFERENCES roles(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS politicas_sla (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NULL,
 nombre VARCHAR(100) NOT NULL, descripcion TEXT,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS reglas_sla (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, politica_sla_id BIGINT NOT NULL,
 prioridad VARCHAR(40) CHECK (prioridad IN ('baja','media','alta','critica')) NOT NULL,
 respuesta_minutos INTEGER NOT NULL, resolucion_minutos INTEGER NOT NULL,
 horario_servicio VARCHAR(40) CHECK (horario_servicio IN ('24x7','laboral')) NOT NULL DEFAULT '24x7',
 FOREIGN KEY(politica_sla_id) REFERENCES politicas_sla(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS contratos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(40) NOT NULL, nombre VARCHAR(180) NOT NULL,
 fecha_inicio DATE NOT NULL, fecha_fin DATE NOT NULL, monto DECIMAL(14,2) NOT NULL DEFAULT 0,
 moneda CHAR(3) NOT NULL DEFAULT 'PEN', estado VARCHAR(40) CHECK (estado IN ('borrador','vigente','por_vencer','vencido','cancelado')) NOT NULL DEFAULT 'borrador',
 politica_sla_id BIGINT NULL, descripcion TEXT,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (fecha_fin >= fecha_inicio),
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(politica_sla_id) REFERENCES politicas_sla(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS servicios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(40) NOT NULL, nombre VARCHAR(180) NOT NULL, descripcion TEXT,
 categoria VARCHAR(100), responsable_id BIGINT NULL,
 contrato_id BIGINT NULL, politica_sla_id BIGINT NULL,
 disponibilidad_objetivo DECIMAL(5,2) NULL,
 estado VARCHAR(40) CHECK (estado IN ('operativo','degradado','interrumpido','mantenimiento','retirado')) NOT NULL DEFAULT 'operativo',
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(responsable_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 FOREIGN KEY(contrato_id) REFERENCES contratos(id) ON DELETE SET NULL,
 FOREIGN KEY(politica_sla_id) REFERENCES politicas_sla(id) ON DELETE SET NULL,
 CHECK (disponibilidad_objetivo IS NULL OR disponibilidad_objetivo BETWEEN 0 AND 100)
);
CREATE TABLE IF NOT EXISTS activos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(40) NOT NULL, nombre VARCHAR(180) NOT NULL,
 tipo VARCHAR(40) CHECK (tipo IN ('servidor','laptop','switch','firewall','vm_cloud','desktop','impresora','otro')) NOT NULL DEFAULT 'otro',
 numero_serie VARCHAR(120), fabricante VARCHAR(120), modelo VARCHAR(120),
 ip VARCHAR(45), hostname VARCHAR(255), ubicacion VARCHAR(180),
 responsable_id BIGINT NULL, servicio_id BIGINT NULL,
 proveedor_cloud VARCHAR(100), region_cloud VARCHAR(100),
 estado VARCHAR(40) CHECK (estado IN ('operativo','asignado','degradado','mantenimiento','fuera_servicio','retirado')) NOT NULL DEFAULT 'operativo',
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(responsable_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 FOREIGN KEY(servicio_id) REFERENCES servicios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS equipos_soporte (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 nombre VARCHAR(120) NOT NULL, descripcion TEXT, activo BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS equipos_miembros (
 equipo_id BIGINT NOT NULL, usuario_id BIGINT NOT NULL,
 PRIMARY KEY(equipo_id,usuario_id),
 FOREIGN KEY(equipo_id) REFERENCES equipos_soporte(id) ON DELETE CASCADE,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(45) NOT NULL UNIQUE, titulo VARCHAR(255) NOT NULL, descripcion TEXT NOT NULL,
 tipo VARCHAR(40) CHECK (tipo IN ('incidente','solicitud','consulta','cambio')) NOT NULL DEFAULT 'incidente',
 categoria VARCHAR(100), subcategoria VARCHAR(100),
 prioridad VARCHAR(40) CHECK (prioridad IN ('baja','media','alta','critica')) NOT NULL DEFAULT 'media',
 impacto VARCHAR(40) CHECK (impacto IN ('bajo','medio','alto')) NOT NULL DEFAULT 'medio',
 urgencia VARCHAR(40) CHECK (urgencia IN ('baja','media','alta')) NOT NULL DEFAULT 'media',
 estado VARCHAR(40) CHECK (estado IN ('abierto','asignado','en_progreso','en_espera','resuelto','cerrado','cancelado')) NOT NULL DEFAULT 'abierto',
 origen VARCHAR(40) CHECK (origen IN ('portal','email','telefono','api','monitorizacion')) NOT NULL DEFAULT 'portal',
 solicitante_id BIGINT NOT NULL, tecnico_id BIGINT NULL,
 equipo_id BIGINT NULL, servicio_id BIGINT NULL,
 activo_id BIGINT NULL, politica_sla_id BIGINT NULL,
 primera_respuesta_en TIMESTAMP NULL, vencimiento_respuesta TIMESTAMP NULL,
 vencimiento_resolucion TIMESTAMP NULL, resuelto_en TIMESTAMP NULL, cerrado_en TIMESTAMP NULL,
 solucion TEXT NULL, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(solicitante_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 FOREIGN KEY(tecnico_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 FOREIGN KEY(equipo_id) REFERENCES equipos_soporte(id) ON DELETE SET NULL,
 FOREIGN KEY(servicio_id) REFERENCES servicios(id) ON DELETE SET NULL,
 FOREIGN KEY(activo_id) REFERENCES activos(id) ON DELETE SET NULL,
 FOREIGN KEY(politica_sla_id) REFERENCES politicas_sla(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS tickets_asignaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
 tecnico_anterior_id BIGINT NULL, tecnico_nuevo_id BIGINT NULL,
 equipo_id BIGINT NULL, asignado_por_id BIGINT NULL,
 motivo VARCHAR(255), fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(tecnico_anterior_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 FOREIGN KEY(tecnico_nuevo_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 FOREIGN KEY(equipo_id) REFERENCES equipos_soporte(id) ON DELETE SET NULL,
 FOREIGN KEY(asignado_por_id) REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS tickets_historial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
 usuario_id BIGINT NULL, campo VARCHAR(100) NOT NULL,
 valor_anterior TEXT, valor_nuevo TEXT, fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS tickets_comentarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
 autor_id BIGINT NOT NULL, contenido TEXT NOT NULL,
 es_interno BOOLEAN NOT NULL DEFAULT FALSE, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(autor_id) REFERENCES usuarios(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS tickets_adjuntos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
 subido_por_id BIGINT NULL, nombre_original VARCHAR(255) NOT NULL,
 ruta_storage VARCHAR(1024) NOT NULL, mime_type VARCHAR(120), tamano_bytes BIGINT,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(subido_por_id) REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS tickets_sla (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL UNIQUE,
 regla_sla_id BIGINT NOT NULL, respuesta_cumplida BOOLEAN NULL,
 resolucion_cumplida BOOLEAN NULL, minutos_pausados INTEGER NOT NULL DEFAULT 0,
 ultima_pausa_en TIMESTAMP NULL, calculado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(regla_sla_id) REFERENCES reglas_sla(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS problemas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(45) NOT NULL UNIQUE, titulo VARCHAR(255) NOT NULL,
 descripcion TEXT, causa_raiz TEXT, solucion_temporal TEXT, solucion_definitiva TEXT,
 servicio_id BIGINT NULL, responsable_id BIGINT NULL,
 estado VARCHAR(40) CHECK (estado IN ('abierto','en_analisis','con_workaround','resuelto','cerrado')) NOT NULL DEFAULT 'abierto',
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, cerrado_en TIMESTAMP NULL,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(servicio_id) REFERENCES servicios(id) ON DELETE SET NULL,
 FOREIGN KEY(responsable_id) REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS incidencias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(45) NOT NULL UNIQUE, ticket_id BIGINT NULL UNIQUE,
 problema_id BIGINT NULL, servicio_id BIGINT NULL,
 descripcion TEXT NOT NULL, impacto VARCHAR(40) CHECK (impacto IN ('bajo','medio','alto')) NOT NULL DEFAULT 'medio',
 urgencia VARCHAR(40) CHECK (urgencia IN ('baja','media','alta')) NOT NULL DEFAULT 'media',
 prioridad VARCHAR(40) CHECK (prioridad IN ('baja','media','alta','critica')) NOT NULL DEFAULT 'media',
 responsable_id BIGINT NULL,
 estado VARCHAR(40) CHECK (estado IN ('abierta','investigando','en_progreso','monitoreando','resuelta','cerrada')) NOT NULL DEFAULT 'abierta',
 inicio_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, resuelta_en TIMESTAMP NULL,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL,
 FOREIGN KEY(problema_id) REFERENCES problemas(id) ON DELETE SET NULL,
 FOREIGN KEY(servicio_id) REFERENCES servicios(id) ON DELETE SET NULL,
 FOREIGN KEY(responsable_id) REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS problemas_tickets (
 problema_id BIGINT NOT NULL, ticket_id BIGINT NOT NULL,
 PRIMARY KEY(problema_id,ticket_id),
 FOREIGN KEY(problema_id) REFERENCES problemas(id) ON DELETE CASCADE,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS solicitudes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 codigo VARCHAR(45) NOT NULL UNIQUE, ticket_id BIGINT NULL UNIQUE,
 titulo VARCHAR(255) NOT NULL, descripcion TEXT,
 solicitante_id BIGINT NOT NULL, aprobador_id BIGINT NULL,
 prioridad VARCHAR(40) CHECK (prioridad IN ('baja','media','alta','critica')) NOT NULL DEFAULT 'media',
 estado VARCHAR(40) CHECK (estado IN ('pendiente_aprobacion','aprobada','rechazada','en_progreso','completada','cancelada')) NOT NULL DEFAULT 'pendiente_aprobacion',
 aprobada_en TIMESTAMP NULL, completada_en TIMESTAMP NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL,
 FOREIGN KEY(solicitante_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 FOREIGN KEY(aprobador_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS articulos_conocimiento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NULL,
 codigo VARCHAR(45) NOT NULL UNIQUE, categoria VARCHAR(100) NOT NULL,
 titulo VARCHAR(255) NOT NULL, resumen TEXT, contenido TEXT NOT NULL,
 autor_id BIGINT NULL, visibilidad VARCHAR(40) CHECK (visibilidad IN ('publica','organizacion','interna')) NOT NULL DEFAULT 'organizacion',
 estado VARCHAR(40) CHECK (estado IN ('borrador','publicado','archivado')) NOT NULL DEFAULT 'borrador',
 vistas INTEGER NOT NULL DEFAULT 0, version INTEGER NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(autor_id) REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS etiquetas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS articulos_etiquetas (
 articulo_id BIGINT NOT NULL, etiqueta_id BIGINT NOT NULL,
 PRIMARY KEY(articulo_id,etiqueta_id),
 FOREIGN KEY(articulo_id) REFERENCES articulos_conocimiento(id) ON DELETE CASCADE,
 FOREIGN KEY(etiqueta_id) REFERENCES etiquetas(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS documentos_rag (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NULL,
 articulo_id BIGINT NULL, nombre VARCHAR(255) NOT NULL,
 fuente_uri VARCHAR(1024), contenido_hash CHAR(64), estado VARCHAR(40) CHECK (estado IN ('pendiente','indexado','error')) NOT NULL DEFAULT 'pendiente',
 indexado_en TIMESTAMP NULL, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(articulo_id) REFERENCES articulos_conocimiento(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS fragmentos_rag (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, documento_id BIGINT NOT NULL,
 numero INTEGER NOT NULL, contenido TEXT NOT NULL,
 embedding_modelo VARCHAR(120), embedding_json JSONB NULL,
 token_count INTEGER,
 FOREIGN KEY(documento_id) REFERENCES documentos_rag(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS modelos_ia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(120) NOT NULL,
 proveedor VARCHAR(100) NOT NULL, version VARCHAR(100), tipo VARCHAR(40) CHECK (tipo IN ('nlp','clasificacion','generativo','embedding','logs')) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE, configuracion JSONB NULL
);
CREATE TABLE IF NOT EXISTS clasificaciones_ia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
 modelo_id BIGINT NULL, categoria_sugerida VARCHAR(100),
 prioridad_sugerida VARCHAR(40) CHECK (prioridad_sugerida IN ('baja','media','alta','critica')),
 confianza DECIMAL(5,4) NULL, explicacion TEXT,
 aceptada BOOLEAN NULL, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (confianza IS NULL OR confianza BETWEEN 0 AND 1),
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(modelo_id) REFERENCES modelos_ia(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS recomendaciones_ia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
 modelo_id BIGINT NULL, diagnostico TEXT, causas_probables JSONB NULL,
 pasos_sugeridos JSONB NULL, confianza DECIMAL(5,4) NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (confianza IS NULL OR confianza BETWEEN 0 AND 1),
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(modelo_id) REFERENCES modelos_ia(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS recomendaciones_fuentes (
 recomendacion_id BIGINT NOT NULL, articulo_id BIGINT NOT NULL,
 relevancia DECIMAL(6,5) NULL,
 PRIMARY KEY(recomendacion_id,articulo_id),
 FOREIGN KEY(recomendacion_id) REFERENCES recomendaciones_ia(id) ON DELETE CASCADE,
 FOREIGN KEY(articulo_id) REFERENCES articulos_conocimiento(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS conversaciones_ia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 usuario_id BIGINT NOT NULL, ticket_id BIGINT NULL,
 titulo VARCHAR(255), creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS mensajes_ia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversacion_id BIGINT NOT NULL,
 rol VARCHAR(40) CHECK (rol IN ('system','user','assistant','tool')) NOT NULL,
 contenido TEXT NOT NULL, modelo_id BIGINT NULL,
 tokens_entrada INTEGER, tokens_salida INTEGER,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(conversacion_id) REFERENCES conversaciones_ia(id) ON DELETE CASCADE,
 FOREIGN KEY(modelo_id) REFERENCES modelos_ia(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS logs_tecnicos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 servicio_id BIGINT NULL, activo_id BIGINT NULL,
 ticket_id BIGINT NULL, origen VARCHAR(180),
 nivel VARCHAR(40) CHECK (nivel IN ('debug','info','warning','error','critical')) NOT NULL DEFAULT 'info',
 mensaje TEXT NOT NULL, metadatos JSONB NULL,
 fecha_evento TIMESTAMP(3) NOT NULL, recibido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(servicio_id) REFERENCES servicios(id) ON DELETE SET NULL,
 FOREIGN KEY(activo_id) REFERENCES activos(id) ON DELETE SET NULL,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS analisis_logs_ia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NOT NULL,
 ticket_id BIGINT NULL, modelo_id BIGINT NULL,
 resumen TEXT NOT NULL, posibles_causas JSONB NULL,
 acciones_recomendadas JSONB NULL, severidad VARCHAR(40) CHECK (severidad IN ('info','warning','error','critical')),
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL,
 FOREIGN KEY(modelo_id) REFERENCES modelos_ia(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS analisis_logs_detalle (
 analisis_id BIGINT NOT NULL, log_id BIGINT NOT NULL,
 PRIMARY KEY(analisis_id,log_id),
 FOREIGN KEY(analisis_id) REFERENCES analisis_logs_ia(id) ON DELETE CASCADE,
 FOREIGN KEY(log_id) REFERENCES logs_tecnicos(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS notificaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NULL,
 usuario_id BIGINT NOT NULL, ticket_id BIGINT NULL,
 titulo VARCHAR(180) NOT NULL, mensaje TEXT NOT NULL,
 tipo VARCHAR(40) CHECK (tipo IN ('ticket','sla','ia','sistema','asignacion')) NOT NULL DEFAULT 'sistema',
 canal VARCHAR(40) CHECK (canal IN ('in_app','email','push')) NOT NULL DEFAULT 'in_app',
 leida_en TIMESTAMP NULL, enviada_en TIMESTAMP NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS preferencias_notificaciones (
 usuario_id BIGINT PRIMARY KEY,
 email_activo BOOLEAN NOT NULL DEFAULT TRUE,
 push_activo BOOLEAN NOT NULL DEFAULT TRUE,
 in_app_activo BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS configuracion_organizacion (
 organizacion_id BIGINT PRIMARY KEY,
 clasificacion_automatica BOOLEAN NOT NULL DEFAULT TRUE,
 prioridad_automatica BOOLEAN NOT NULL DEFAULT FALSE,
 rag_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
 zona_horaria VARCHAR(60) NOT NULL DEFAULT 'America/Lima',
 configuracion JSONB NULL,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organizacion_id BIGINT NULL,
 usuario_id BIGINT NULL, entidad VARCHAR(100) NOT NULL,
 entidad_id BIGINT NULL, accion VARCHAR(80) NOT NULL,
 datos_antes JSONB NULL, datos_despues JSONB NULL,
 ip_origen VARCHAR(45), fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(organizacion_id) REFERENCES organizaciones(id) ON DELETE SET NULL,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);



