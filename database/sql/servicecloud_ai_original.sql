-- Catálogo de categorías: evita variaciones de texto para una misma clasificación.
CREATE TABLE IF NOT EXISTS categorias_tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id BIGINT NOT NULL REFERENCES organizaciones(id) ON DELETE RESTRICT,
 nombre VARCHAR(120) NOT NULL,
 padre_id BIGINT NULL REFERENCES categorias_tickets(id) ON DELETE RESTRICT,
 UNIQUE (organizacion_id,nombre), UNIQUE (organizacion_id,id),
 FOREIGN KEY (organizacion_id,padre_id) REFERENCES categorias_tickets(organizacion_id,id)
);
ALTER TABLE tickets ADD COLUMN categoria_id BIGINT NULL;
ALTER TABLE tickets ADD CONSTRAINT fk_ticket_categoria_tenant FOREIGN KEY (organizacion_id,categoria_id) REFERENCES categorias_tickets(organizacion_id,id);

-- Relación N:M entre servicios y activos (un activo puede soportar varios servicios).
CREATE TABLE IF NOT EXISTS servicios_activos (
 organizacion_id BIGINT NOT NULL REFERENCES organizaciones(id) ON DELETE RESTRICT,
 servicio_id BIGINT NOT NULL,
 activo_id BIGINT NOT NULL,
 PRIMARY KEY (servicio_id,activo_id),
 FOREIGN KEY (organizacion_id,servicio_id) REFERENCES servicios(organizacion_id,id) ON DELETE CASCADE,
 FOREIGN KEY (organizacion_id,activo_id) REFERENCES activos(organizacion_id,id) ON DELETE CASCADE
);

-- Asignación de roles por organización, en lugar de roles globales implícitos.
CREATE TABLE IF NOT EXISTS usuarios_roles_organizacion (
 organizacion_id BIGINT NOT NULL REFERENCES organizaciones(id) ON DELETE CASCADE,
 usuario_id BIGINT NOT NULL,
 rol_id SMALLINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
 PRIMARY KEY (organizacion_id,usuario_id,rol_id),
 FOREIGN KEY (organizacion_id,usuario_id) REFERENCES usuarios(organizacion_id,id) ON DELETE CASCADE
);

